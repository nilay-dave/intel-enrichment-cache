"""Writes docs/measurements.md from docs/metrics.json, and verifies it is current.

A hand written results table is correct on the day it is written and silently
wrong after the next benchmark run. Generating it means the only way the
document can disagree with the measurement is if somebody forgets to run this,
and --check in CI is what stops that.

The generated page keeps the real and the simulated figures in separate
sections with separate headings, because the distinction is the most important
thing on the page and a reader skimming a table will not notice a suffix.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
METRICS = ROOT / "docs" / "metrics.json"
TARGET = ROOT / "docs" / "measurements.md"


def render(data: dict) -> str:
    lines: list[str] = []
    add = lines.append

    add("# Measurements")
    add("")
    add("Generated by `tools/generate_measurements_doc.py` from `docs/metrics.json`.")
    add("Reproduce the whole thing with `make bench`.")
    add("")

    model = data["stream_model"]
    add("## The stream these numbers come from")
    add("")
    add(
        f"Generated, not captured: a Zipf repeat distribution at alpha {model['alpha']} over a universe "
        f"{model['universe_ratio']:.0%} the length of the stream, arriving in bursts of "
        f"{model['burst_size_mean']:.0f} on average spread over {model['burst_spread_seconds']:.0f} seconds, "
        f"across a simulated {model['duration_days']:.0f} days."
    )
    add("")
    add(f"_{model['indicators_drawn_independently_of_burst']}_")
    add("")

    add("## Real: what the cache and the coalescer are worth")
    add("")
    add(
        "No latency model is involved in these. A request count is a property of the algorithm on a "
        "stated stream and does not depend on how long a request takes, so the experiment that produces "
        "them removes latency entirely."
    )
    add("")
    add("| lookups | days | cache hit rate | coalesced | requests per 1,000 | lookups a free tier supports |")
    add("| --- | --- | --- | --- | --- | --- |")
    for entry in data["quota_efficiency"]:
        supported = entry["virustotal_public_lookups_per_day"]
        add(
            f"| {entry['lookups']:,} | {entry['simulated_days_elapsed']:.1f} | "
            f"{entry['cache_hit_rate']:.3f} | {entry['coalesced']:,} | "
            f"{entry['requests_per_1000_lookups']:.1f} | "
            f"{supported:,} a day |" if supported is not None else "| (no measurement) |"
        )
    add("")
    biggest = data["quota_efficiency"][-1]
    uncached = biggest["virustotal_public_lookups_per_day_uncached"]
    cached = biggest["virustotal_public_lookups_per_day"]
    add(
        f"The last column is the point of the library. VirusTotal's public tier allows {uncached} requests "
        f"a day, so an uncached client enriches {uncached} indicators a day and then stops. At the measured "
        f"request rate the same allowance covers about {cached:,} lookups a day, which is "
        f"{cached / uncached:.1f} times as many."
    )
    add("")
    add("## Real: what a cache lifetime policy costs")
    add("")
    add("| policy | cache hit rate | requests per 1,000 lookups |")
    add("| --- | --- | --- |")
    for entry in data["ttl_policy"]:
        add(
            f"| `{entry['policy']}` | {entry['cache_hit_rate']:.3f} | "
            f"{entry['requests_per_1000_lookups']:.1f} |"
        )
    add("")
    per_class = next(entry for entry in data["ttl_policy"] if entry["policy"] == "per_class_defaults")
    longest = max(data["ttl_policy"], key=lambda entry: entry["cache_hit_rate"])
    add(
        f"A uniform {longest['policy'].replace('uniform_', '')} lifetime reaches a "
        f"{longest['cache_hit_rate']:.3f} hit rate against {per_class['cache_hit_rate']:.3f} for the per "
        f"class defaults, at "
        f"{per_class['requests_per_1000_lookups'] / longest['requests_per_1000_lookups']:.1f} times fewer "
        "requests. On hit rate alone the per class policy loses decisively, which is why hit rate is the "
        "wrong criterion: a longer lifetime always scores better, up to never expiring anything, which "
        "would score perfectly and be useless. What this table measures is the price of the safety, and "
        "[ADR-001](adr/adr-001-cache-lifetime.md) is the argument about whether to pay it."
    )
    add("")

    latency = data["latency_model_simulated"]
    add("## Simulated: what hedging buys and costs")
    add("")
    add(
        "**The latency figures below are a simulation.** There is no API behind them. They come from a "
        f"lognormal body with a median of {latency['median_ms']:.0f}ms and sigma {latency['sigma']}, plus "
        f"{latency['stall_rate']:.0%} of responses stalling at {latency['stall_multiplier']:.0f} times the "
        "median, and they are only as good as that model. The request counts in the same table are real."
    )
    add("")
    add("| policy | p50 | p95 | p99 | requests | extra requests | p99 change |")
    add("| --- | --- | --- | --- | --- | --- | --- |")
    for entry in data["hedging"]:
        add(
            f"| `{entry['policy']}` | {entry['p50_ms_simulated']:.0f}ms | "
            f"{entry['p95_ms_simulated']:.0f}ms | {entry['p99_ms_simulated']:.0f}ms | "
            f"{entry['provider_requests']:,} | +{entry['extra_request_percent']:.2f}% | "
            f"{entry['p99_change_percent']:+.1f}% |"
        )
    add("")
    sample = data["hedging"][0]["lookups"]
    add(
        f"Percentiles are nearest rank over {sample:,} lookups, so the p99 is the "
        f"{max(1, round(sample * 0.01))}th slowest observation rather than an interpolation between two "
        "that were never seen."
    )
    add("")
    best = min(data["hedging"][1:], key=lambda entry: entry["p99_ms_simulated"])
    add(
        f"The module's own docstring used to argue that hedging is expensive on a metered API. It is not: "
        f"a hedge only fires on a request that has already stalled, so its cost is bounded by the "
        f"{latency['stall_rate']:.0%} stall rate rather than by the traffic. Hedging "
        f"{best['policy'].replace('after_', 'after ')} cut the simulated p99 by "
        f"{abs(best['p99_change_percent']):.0f}% for {best['extra_request_percent']:.1f}% more requests. "
        "The docstring now says so."
    )
    add("")
    add(
        "It is still off by default. 5% more requests is cheap and it is still 5% a caller did not ask "
        "for, and the stall rate it depends on belongs to somebody else's service: a provider having a "
        "bad hour is exactly when the stall rate climbs, which is exactly when the budget can least "
        "absorb it. That is what the quota floor is for."
    )
    add("")
    add("## What is not measured here")
    add("")
    add(
        "How long a verdict stays true, which is the thing that would settle the cache lifetime defaults. "
        "No replay of an indicator stream can supply it: the stream records what was looked up, not what "
        "the answer would have been at other times. See [limitations](limitations.md)."
    )
    add("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the file on disk differs")
    args = parser.parse_args(argv)

    if not METRICS.is_file():
        print(f"{METRICS} is absent. Run: make bench", file=sys.stderr)
        return 1

    rendered = render(json.loads(METRICS.read_text(encoding="utf-8")))
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if current != rendered:
            print(f"{TARGET} is out of date. Run: python tools/generate_measurements_doc.py", file=sys.stderr)
            return 1
        print(f"{TARGET.name} matches the metrics")
        return 0

    TARGET.write_text(rendered, encoding="utf-8")
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
